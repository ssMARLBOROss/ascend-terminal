import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source=fs.readFileSync('fvg-research-v1.js','utf8');
const page=fs.readFileSync('index.html','utf8');
const scope={};
new vm.Script(source);
vm.runInNewContext(source,scope);
const F=scope.ASCEND_FVG_RESEARCH_V1;
assert.ok(F&&typeof F.scan==='function');
const D=Date.UTC(2026,9,12)/1000;
const bar=i=>({time:D+i*180,open:100,high:101,low:99,close:100,volume:10});
const baseline=Array.from({length:24},(_,i)=>bar(i));
baseline[20]={...baseline[20],open:103,high:105,low:102,close:104};
const at=baseline[20].time+180;
const whenOpen=F.scan(baseline,baseline[20].time+90);
assert.equal(whenOpen.some(x=>x.formedAt===at),false,'cannot use forming 3m candle');
const formed=F.scan(baseline,at);
const current=formed.find(x=>x.formedAt===at);
assert.ok(current,'closed third candle forms FVG');
assert.equal(current.side,'LONG');
assert.equal(current.lower,101);
assert.equal(current.upper,102);
assert.equal(current.status,'OPEN');
assert.equal(current.firstTouchAt,null);
assert.equal(current.fillFraction,0);
const partial=baseline.map(x=>({...x}));
partial[21]={...partial[21],open:102.4,high:103,low:101.5,close:102.2};
const p=F.scan(partial,partial[21].time+180).find(x=>x.formedAt===at);
assert.equal(p.status,'PARTIAL');
assert.ok(p.fillFraction>.4&&p.fillFraction<.6);
assert.equal(p.firstTouchAt,partial[21].time+180);
const filled=baseline.map(x=>({...x}));
filled[21]={...filled[21],open:102,high:103,low:100.8,close:101};
const full=F.scan(filled,filled[21].time+180).find(x=>x.formedAt===at);
assert.equal(full.status,'FILLED');
assert.equal(full.fillFraction,1);
const mirror=baseline.map(x=>({time:x.time,open:210-x.open,
 high:210-x.low,low:210-x.high,close:210-x.close,volume:x.volume}));
const bearish=F.scan(mirror,at).find(x=>x.formedAt===at);
assert.equal(bearish.side,'SHORT');
assert.equal(bearish.lower,108);
assert.equal(bearish.upper,109);
assert.equal(F.observe(baseline,at,'LONG').status,'RESEARCH');
assert.equal(F.observe([],at).status,'NO DATA');
assert.ok(page.includes(source.trim()),'live Cloudflare inline FVG code equals source');
assert.ok(page.includes('id="ascResearchFvg"'));
assert.ok(page.includes('id="ascResearchParticipation"'));
const research=fs.readFileSync('research-panel-v1.js','utf8');
assert.ok(page.includes(research.trim()),'live UI source parity');
for(const [i,match] of [...page.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].entries())
 if(match[1].trim())new vm.Script(match[1],{filename:'inline-'+i+'.js'});
console.log('PASS research FVG: causal 3m, open/partial/filled, bullish/bearish, UI source parity');
